import {
  DocumentNode,
  getNamedType,
  GraphQLNamedType,
  GraphQLSchema,
  isInputObjectType,
  isInterfaceType,
  isNonNullType,
  isObjectType,
  isScalarType,
  isSpecifiedScalarType,
  isTypeExtensionNode,
  isUnionType,
  Kind,
} from 'graphql'
import {
  ENTRY_DIRECTIVE_NAME,
  hasDirective,
  SEARCHABLE_DIRECTIVE_NAME,
} from './schema-utils/directive-util.ts'
import { isUnionOfEntryTypes } from './schema-utils/entry-type-util.ts'
import * as names from './schema-utils/generated-names.ts'

/**
 * Returns the types defined in the schema by the user, i.e. without introspection types and built-in scalars.
 */
function getUserTypes(schema: GraphQLSchema): GraphQLNamedType[] {
  return Object.values(schema.getTypeMap()).filter(
    (type) =>
      !type.name.startsWith('__') &&
      !(isScalarType(type) && isSpecifiedScalarType(type)),
  )
}

/**
 * Rejects GraphQL constructs that Commitspark does not support, so that they do not silently lead to unexpected
 * behavior or an invalid generated schema. Only object types, unions, enums, built-in scalars and directives are
 * supported.
 */
function checkSupportedConstructs(
  schema: GraphQLSchema,
  document: DocumentNode,
): string[] {
  const results: string[] = []

  // schema definitions and type extensions are detected in the document, as building the schema merges type
  // extensions into their types and adds a schema definition for root types
  for (const definition of document.definitions) {
    if (
      definition.kind === Kind.SCHEMA_DEFINITION ||
      definition.kind === Kind.SCHEMA_EXTENSION
    ) {
      results.push(
        'Schema definitions ("schema { ... }") are not supported, as Commitspark generates the root types.',
      )
    } else if (isTypeExtensionNode(definition)) {
      results.push(
        `Type extensions ("extend") of "${definition.name.value}" are not supported; declare the type in a ` +
          `single definition.`,
      )
    }
  }

  for (const type of getUserTypes(schema)) {
    if (isInterfaceType(type)) {
      results.push(
        `Interface "${type.name}" is not supported; use a union instead.`,
      )
    } else if (isInputObjectType(type)) {
      results.push(
        `Input type "${type.name}" is not supported, as Commitspark generates input types.`,
      )
    } else if (isScalarType(type)) {
      results.push(
        `Custom scalar "${type.name}" is not supported; use one of the built-in scalars "String", "Int", ` +
          `"Float", "Boolean" and "ID".`,
      )
    }

    if (isObjectType(type)) {
      for (const field of Object.values(type.getFields())) {
        if (field.args.length > 0) {
          results.push(
            `Field "${type.name}.${field.name}" has arguments, which are not supported.`,
          )
        }
      }
    }
  }

  return results
}

/**
 * Maps a generated name to descriptions of what it is generated for, e.g. `'the input type of type "Product"'`.
 * A name with more than one description is generated more than once.
 */
type GeneratedNames = Map<string, string[]>

function addGeneratedName(
  generatedNames: GeneratedNames,
  name: string,
  description: string,
): void {
  generatedNames.set(name, [...(generatedNames.get(name) ?? []), description])
}

function describeDuplicates(
  generatedNames: GeneratedNames,
  kind: string,
): string[] {
  return [...generatedNames.entries()]
    .filter(([, descriptions]) => descriptions.length > 1)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([name, descriptions]) =>
        `Generated ${kind} name "${name}" would be used for ${descriptions.join(' and for ')}; rename one of ` +
        `the types.`,
    )
}

/**
 * Rejects names that collide with names generated by Commitspark, as generated and user definitions with the same
 * name would otherwise be merged or fail with an unspecific error.
 */
function checkGeneratedNameCollisions(schema: GraphQLSchema): string[] {
  const userTypes = getUserTypes(schema)
  const objectTypes = userTypes.filter((type) => isObjectType(type))
  const entryTypes = objectTypes.filter((type) =>
    hasDirective(type, ENTRY_DIRECTIVE_NAME),
  )
  const unionTypes = userTypes.filter((type) => isUnionType(type))

  const typeNames: GeneratedNames = new Map()
  for (const name of [
    names.QUERY_TYPE_NAME,
    names.MUTATION_TYPE_NAME,
    names.SUBSCRIPTION_TYPE_NAME,
  ]) {
    addGeneratedName(typeNames, name, 'a root type')
  }
  for (const name of [
    names.COMMIT_INPUT_TYPE_NAME,
    names.SEARCH_HIT_TYPE_NAME,
  ]) {
    addGeneratedName(typeNames, name, 'a type of Commitspark')
  }
  for (const type of objectTypes) {
    addGeneratedName(
      typeNames,
      names.inputTypeName(type.name),
      `the input type of type "${type.name}"`,
    )
  }
  for (const type of entryTypes) {
    addGeneratedName(
      typeNames,
      names.idInputTypeName(type.name),
      `the reference input type of type "${type.name}"`,
    )
  }
  for (const type of unionTypes) {
    if (isUnionOfEntryTypes(type)) {
      addGeneratedName(
        typeNames,
        names.idInputTypeName(type.name),
        `the reference input type of union "${type.name}"`,
      )
    } else {
      addGeneratedName(
        typeNames,
        names.inputTypeName(type.name),
        `the input type of union "${type.name}"`,
      )
    }
  }

  const queryNames: GeneratedNames = new Map()
  const mutationNames: GeneratedNames = new Map()
  addGeneratedName(
    queryNames,
    names.TYPE_NAME_QUERY_NAME,
    'a query of Commitspark',
  )
  addGeneratedName(
    queryNames,
    names.SEARCH_QUERY_NAME,
    'a query of Commitspark',
  )
  for (const type of entryTypes) {
    addGeneratedName(
      queryNames,
      names.queryEveryName(type.name),
      `the query of all entries of type "${type.name}"`,
    )
    addGeneratedName(
      queryNames,
      names.queryByIdName(type.name),
      `the query of a single entry of type "${type.name}"`,
    )
    for (const [mutationName, operation] of [
      [names.createMutationName(type.name), 'create'],
      [names.updateMutationName(type.name), 'update'],
      [names.deleteMutationName(type.name), 'delete'],
    ]) {
      addGeneratedName(
        mutationNames,
        mutationName,
        `the ${operation} mutation of type "${type.name}"`,
      )
    }
  }

  const results: string[] = []
  for (const type of userTypes) {
    const descriptions = typeNames.get(type.name)
    if (descriptions !== undefined) {
      results.push(
        `Type name "${type.name}" is reserved for ${descriptions.join(' and for ')}; rename the type.`,
      )
    }
  }
  results.push(...describeDuplicates(typeNames, 'type'))
  results.push(...describeDuplicates(queryNames, 'query'))
  results.push(...describeDuplicates(mutationNames, 'mutation'))

  for (const type of entryTypes) {
    for (const fieldName of [
      names.REFERENCED_BY_FIELD_NAME,
      names.VERSION_FIELD_NAME,
    ]) {
      if (type.getFields()[fieldName] !== undefined) {
        results.push(
          `Field name "${type.name}.${fieldName}" is reserved for a field that Commitspark adds to every type with ` +
            `"@${ENTRY_DIRECTIVE_NAME}" directive; rename the field.`,
        )
      }
    }
  }

  return results
}

function checkUnionMembersConsistentUseOfEntryDirective(
  schema: GraphQLSchema,
): string[] {
  return getUserTypes(schema)
    .filter((type) => isUnionType(type))
    .filter((type) => {
      const members = type.getTypes()
      const numberMembersWithEntryDirective = members.filter((member) =>
        hasDirective(member, ENTRY_DIRECTIVE_NAME),
      ).length
      return (
        numberMembersWithEntryDirective !== 0 &&
        numberMembersWithEntryDirective !== members.length
      )
    })
    .map(
      (type) =>
        `Either all union members of "${type.name}" must have "@${ENTRY_DIRECTIVE_NAME}" directive or none.`,
    )
}

function checkSearchableDirectiveOnlyOnStringFields(
  schema: GraphQLSchema,
): string[] {
  const results: string[] = []
  for (const type of getUserTypes(schema)) {
    if (!isObjectType(type)) {
      continue
    }
    for (const field of Object.values(type.getFields())) {
      if (!hasDirective(field, SEARCHABLE_DIRECTIVE_NAME)) {
        continue
      }
      const namedType = getNamedType(field.type)
      if (!isScalarType(namedType) || namedType.name !== 'String') {
        results.push(
          `Field "${type.name}.${field.name}" must be of type "String" or a list of "String" to use ` +
            `"@${SEARCHABLE_DIRECTIVE_NAME}" directive.`,
        )
      }
    }
  }
  return results
}

function checkEntryTypesHaveIdField(schema: GraphQLSchema): string[] {
  return getUserTypes(schema)
    .filter(
      (type) => isObjectType(type) && hasDirective(type, ENTRY_DIRECTIVE_NAME),
    )
    .filter((type) => {
      const idField = isObjectType(type) ? type.getFields()['id'] : undefined
      return (
        idField === undefined ||
        !isNonNullType(idField.type) ||
        !isScalarType(idField.type.ofType) ||
        idField.type.ofType.name !== 'ID'
      )
    })
    .map(
      (type) =>
        `Type "${type.name}" must have a field "id" of type "ID!" to use "@${ENTRY_DIRECTIVE_NAME}" directive.`,
    )
}

/**
 * Validates the schema defined by the user and returns a message for every problem found. `document` is the parsed
 * schema definition the schema was built from.
 */
export function getValidationResult(
  schema: GraphQLSchema,
  document: DocumentNode,
): string[] {
  return [
    ...checkSupportedConstructs(schema, document),
    ...checkGeneratedNameCollisions(schema),
    ...checkEntryTypesHaveIdField(schema),
    ...checkUnionMembersConsistentUseOfEntryDirective(schema),
    ...checkSearchableDirectiveOnlyOnStringFields(schema),
  ]
}
